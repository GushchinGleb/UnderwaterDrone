float f_sin_f(float x) {
  const float id = x * (F_1PI * 256.f * 2.0f);
  const uint8_t id_i = id;

  const float l_val = lookup_table_256[id_i]; // left lookup value
  const float r_val = lookup_table_256[id_i + 1]; // right lookup value

  const float diff = id - id_i; // real position of index
  const float result = l_val + (r_val - l_val) * diff; // linear approximation

  return result;
}